"""Repository composition for local storage and future production database adapters.

The production application can pass RepositoryBundle to create_app. Media
repositories provide local working paths for render/upload operations, even when
their durable bytes are stored in a database. Existing local paths are retained.
"""

import os
from dataclasses import dataclass
from pathlib import Path
from typing import Protocol


FEATURE_ROOT = Path(__file__).resolve().parents[1]


def runtime_base(root):
    """Keep injected roots isolated and store default runtime data beside the feature."""
    root = Path(root)
    return FEATURE_ROOT.parent if root.resolve() == FEATURE_ROOT else root


class PrevisJobRepository(Protocol):
    def track_execution(self, job_id, task): ...
    def prompt_context(self, session_id, *, new_scene=False): ...
    def create(self, message, session_id=None, duration=5, aspect='16:9', new_scene=False, *,
               scenario_titles=None, work_settings=None): ...
    def checkpoint(self, job): ...
    def versions(self, session_id): ...
    def emit(self, job_id, kind, value): ...
    def heartbeat(self, job_id): ...
    def finish(self, job, output=None, error=None): ...
    def get(self, job_id, after=-1): ...
    def replace_media(self, job_id, index, item): ...
    def scene_prompt(self, job_id): ...
    def history_snapshot(self): ...
    def completed_sources(self, limit=20): ...
    def refresh_media(self, job_id, index, **fields): ...


class VideoJobRepository(Protocol):
    def make_permanent(self): ...
    def register_characters(self, records): ...
    def save_character_voices(self, profiles): ...
    def create(self, request_id, source, options, *, initial_metadata=None): ...
    def get(self, job_id): ...
    def recent(self): ...
    def unfinished(self): ...
    def all_jobs(self): ...
    def for_source(self, source_id): ...
    def for_sources(self, source_ids): ...
    def claim(self, job_id, owner=None): ...
    def begin_submission(self, job_id, owner): ...
    def publish_result(self, job_id, owner, candidate, target): ...
    def update(self, job_id, *, owner=None, **values): ...
    def heartbeat(self, job_id, owner=None): ...


class AssetRepository(Protocol):
    def save(self, content, role, name): ...
    def get(self, asset_id): ...
    def resolve(self, asset_ids): ...


class UploadedPrevisRepository(Protocol):
    api_prefix: str
    async def save(self, file, scene_prompt=""): ...
    def get(self, source_id): ...
    def recent(self): ...


class ArchiveRepository(Protocol):
    def make_permanent(self): ...
    def safe_path(self, relative): ...
    def record(self, key): ...
    def track(self, key, path, *, created=None, reuse_path=False): ...
    def path(self, key, *, now=None): ...
    def save_scene_reference(self, job): ...
    def scene_reference(self, job_id): ...
    def previs(self, job_id, index): ...
    def previs_results(self): ...
    async def save(self, job_id, index, item, *, created=None): ...
    def complete(self, job_id, items, *, completed=None): ...
    def cleanup(self, *, now=None): ...


class HistoryRepository(Protocol):
    def save_previs(self, job, state, **kwargs): ...
    def record_usage(self, job_id, row): ...
    def record_video_source(self, video): ...
    def list_records(self, service, manager, **kwargs): ...
    def details(self, job_id, service, manager): ...
    def delete(self, job_id): ...
    def set_hidden(self, job_id, hidden): ...
    def set_note(self, job_id, note): ...


@dataclass(frozen=True)
class RepositoryBundle:
    previs_jobs: PrevisJobRepository
    video_jobs: VideoJobRepository
    assets: AssetRepository
    uploaded_previs: UploadedPrevisRepository
    archive: ArchiveRepository
    history: HistoryRepository


def local_repositories(root, *, transport=None):
    mode = os.getenv("PREVIS_STORAGE_MODE", "server")
    if mode == "local-files":
        from local_support.repositories import file_repositories

        return file_repositories(runtime_base(root).resolve(), transport=transport)
    if mode != "server":
        raise ValueError("PREVIS_STORAGE_MODE must be server or local-files")
    from .store import JobStore
    from .job_repository import VideoJobs
    from .video_media import VideoAssets, UploadedPrevis
    from .media_archive import MediaArchive
    from .usage_history import UsageHistory

    storage_root = runtime_base(root)
    data_root = storage_root / "runtime/data"
    archive = MediaArchive(storage_root, transport=transport)
    return RepositoryBundle(
        previs_jobs=JobStore(),
        video_jobs=VideoJobs(data_root / "wan-jobs.sqlite3", label="영상",
                             completion_message="영상이 생성되었습니다. 영구 보관됩니다."),
        assets=VideoAssets(storage_root),
        uploaded_previs=UploadedPrevis(storage_root, archive, api_prefix="/api/video"),
        archive=archive,
        history=UsageHistory(storage_root / "runtime/archive/usage-history.sqlite3"),
    )
